/**
 * Provider-neutral file storage (Phase 5, §5.5) — SERVER-SIDE ONLY.
 *
 * The application depends on this small surface, not on a vendor
 * SDK or on filesystem calls scattered through routes:
 *
 *   - saveFile(buffer, extension) -> { filename, url }
 *   - deleteFile(url) / deleteFiles(urls)
 *   - storedFileNameFromUrl(url)
 *   - resolveStoredFilePath(filename)
 *   - fileUrl(filename)
 *
 * The only implementation today is local disk, backed by
 * UPLOAD_DIR (default <project>/public/uploads) and the historical
 * public URL shape "/uploads/<filename>". Keeping those names and
 * URLs stable means product records, legacy data-URLs, and external
 * image URLs do not need migration. A future object-storage
 * implementation can satisfy this same surface, but it is NOT
 * implemented here: it needs a provider account/credentials and the
 * owner's hosting decision.
 *
 * SERVING: files are served by the route handler at
 * src/app/uploads/[filename]/route.ts via readStoredFile() below —
 * NOT by Next.js static `public/` serving. The production server
 * only serves `public/` files that existed when it started, so a
 * freshly uploaded image 404'd until a restart (the product-create
 * "uploaded image does not display" bug). The route handler reads
 * from storageDirPath() on every request, so new uploads display
 * immediately in dev and production, and a custom UPLOAD_DIR works
 * without exposing it through `public/`.
 *
 * Safety: stored filenames are generated by this module (timestamp
 * + random suffix + a validated extension). Deletion accepts only
 * app-minted "/uploads/<single filename>" URLs; data-URLs, external
 * URLs, nested paths, and traversal attempts are ignored. The
 * resolved path is also checked against the storage directory.
 */
import { promises as fs } from "fs";
import path from "path";
import crypto from "crypto";

export interface StoredFile {
   filename: string;
   url: string;
   path: string;
}

/** Absolute directory used by the local-disk implementation. */
export function storageDirPath(): string {
   return path.resolve(
      process.env.UPLOAD_DIR || path.join(process.cwd(), "public", "uploads"),
   );
}

/** Public URL for a stored filename (stable legacy URL shape). */
export function fileUrl(filename: string): string {
   return `/uploads/${filename}`;
}

/**
 * Extract a plain stored filename from an app-minted upload URL.
 * Returns null for data-URLs, external URLs, empty values, nested
 * paths, and traversal attempts. Pure.
 */
export function storedFileNameFromUrl(url: unknown): string | null {
   if (typeof url !== "string") return null;
   const prefix = "/uploads/";
   if (!url.startsWith(prefix)) return null;
   const name = url.slice(prefix.length);
   if (!name) return null;
   if (name.includes("/") || name.includes("\\") || name.includes("..")) {
      return null;
   }
   return name;
}

/**
 * Resolve a plain filename inside the storage directory, or null
 * when the name is path-like or the resolved path would escape.
 */
export function resolveStoredFilePath(filename: unknown): string | null {
   if (typeof filename !== "string" || !filename) return null;
   if (
      filename.includes("/") ||
      filename.includes("\\") ||
      filename.includes("..")
   ) {
      return null;
   }
   const dir = storageDirPath();
   const target = path.resolve(dir, filename);
   return target.startsWith(dir + path.sep) ? target : null;
}

const CONTENT_TYPE_BY_EXT: Record<string, string> = {
   ".png": "image/png",
   ".jpg": "image/jpeg",
   ".jpeg": "image/jpeg",
   ".webp": "image/webp",
   ".gif": "image/gif",
   ".avif": "image/avif",
};

/**
 * MIME type for a stored filename, derived from its extension.
 * Only the raster types the uploads route can mint are servable;
 * anything else returns null so the serving route 404s instead of
 * handing out arbitrary files from the storage directory. Pure.
 */
export function storedFileContentType(filename: unknown): string | null {
   if (typeof filename !== "string") return null;
   const dot = filename.lastIndexOf(".");
   if (dot < 0) return null;
   return CONTENT_TYPE_BY_EXT[filename.slice(dot).toLowerCase()] ?? null;
}

export interface ReadStoredFile {
   buffer: Buffer;
   contentType: string;
}

/**
 * Read one stored file for serving. Returns null for path-like or
 * traversal names, non-image extensions, and missing files — the
 * caller turns null into a 404.
 */
export async function readStoredFile(
   filename: unknown,
): Promise<ReadStoredFile | null> {
   const contentType = storedFileContentType(filename);
   if (!contentType) return null;
   const target = resolveStoredFilePath(filename);
   if (!target) return null;
   try {
      const buffer = await fs.readFile(target);
      return { buffer, contentType };
   } catch {
      return null;
   }
}

/** Save bytes under a generated filename and return its public URL. */
export async function saveFile(
   buffer: Buffer,
   extension: string,
): Promise<StoredFile> {
   if (!/^\.[a-z0-9]+$/i.test(extension)) {
      throw new Error(`Invalid stored-file extension: ${extension}`);
   }
   const filename = `${Date.now()}-${crypto.randomBytes(6).toString("hex")}${extension.toLowerCase()}`;
   const dir = storageDirPath();
   const target = path.join(dir, filename);
   await fs.mkdir(dir, { recursive: true });
   await fs.writeFile(target, buffer);
   return { filename, url: fileUrl(filename), path: target };
}

/**
 * Delete one app-minted uploaded file by URL. Best-effort by
 * design: returns false for foreign URLs and missing files, and
 * logs (then swallows) filesystem errors so cleanup can never fail
 * the business operation that triggered it.
 */
export async function deleteFile(url: unknown): Promise<boolean> {
   const filename = storedFileNameFromUrl(url);
   if (!filename) return false;
   const target = resolveStoredFilePath(filename);
   if (!target) return false;
   try {
      await fs.unlink(target);
      return true;
   } catch (error: any) {
      if (error?.code !== "ENOENT") {
         console.error(`Failed to delete uploaded file ${filename}:`, error);
      }
      return false;
   }
}

/** Delete several app-minted uploaded files, sequentially. */
export async function deleteFiles(urls: Iterable<unknown>): Promise<void> {
   for (const url of urls) {
      await deleteFile(url);
   }
}
